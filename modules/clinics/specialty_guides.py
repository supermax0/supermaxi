def list_guide_catalog() -> list[dict]:
    """All known system specialties with guide availability."""
    rows = []
    for code, name_ar, name_en in DEFAULT_SPECIALTIES:
        pack = SPECIALTY_GUIDE_PACKS.get(code) or {}
        rows.append(
            {
                "code": code,
                "name_ar": name_ar,
                "name_en": name_en,
                "has_guide": True,
                "focus": pack.get("focus") or "دليل تشغيل عام للعيادة والمعاينة.",
            }
        )
    return rows


def guide_pack(code: str) -> dict:
    key = str(code or "").strip().lower()
    base_name = next((n for c, n, _ in DEFAULT_SPECIALTIES if c == key), None)
    pack = dict(SPECIALTY_GUIDE_PACKS.get(key) or {})
    if not base_name and not pack:
        raise ValueError("دليل الاختصاص غير موجود")
    name_ar = base_name or pack.get("name_ar") or key
    name_en = next((e for c, _, e in DEFAULT_SPECIALTIES if c == key), "")
    return {
        "code": key or "general_medicine",
        "name_ar": name_ar,
        "name_en": name_en,
        "focus": pack.get("focus") or "تشغيل المعاينة الطبية لهذا الاختصاص ضمن مسار العيادة.",
        "services": pack.get("services") or ["استشارة", "مراجعة", "متابعة"],
        "complaint_example": pack.get("complaint_example") or "شكوى رئيسية مختصرة",
        "exam_focus": pack.get("exam_focus") or ["الفحص العام", "الملاحظات السريرية"],
        "tips": pack.get("tips")
        or [
            ("الحساسية", "راجع الحساسية قبل الوصفة."),
            ("التحقق", "تأكد من هوية المريض قبل إنهاء الزيارة."),
            ("الخدمة", "اربط الزيارة بالخدمة الصحيحة للفاتورة."),
            ("المتابعة", "حدّد موعد متابعة عند الحاجة."),
        ],
        "training_complaint": pack.get("training_complaint") or "شكوى تجريبية للتدريب",
        "training_service": pack.get("training_service") or (pack.get("services") or ["استشارة"])[0],
    }


def build_guide_context(
    *,
    code: str,
    clinic_name: str,
    organization_mode: str,
    tenant_slug: str,
    booking_enabled: bool = True,
    active_specialty_codes: list[str] | None = None,
) -> dict:
    pack = guide_pack(code)
    org_labels = {
        "solo_clinic": "طبيب واحد (solo_clinic)",
        "multi_doctor_clinic": "عيادة متعددة الأطباء",
        "medical_center": "مجمع طبي",
    }
    active = active_specialty_codes or []
    return {
        **pack,
        "clinic_name": clinic_name or "عيادة Finora",
        "organization_mode": organization_mode or "solo_clinic",
        "organization_label": org_labels.get(organization_mode, organization_mode or "—"),
        "tenant_slug": tenant_slug or "",
        "booking_path": f"/c/{tenant_slug}" if tenant_slug else "/c/{tenant_slug}",
        "booking_enabled": bool(booking_enabled),
        "specialty_active": pack["code"] in active if active else True,
        "guide_version": "1.0",
    }
