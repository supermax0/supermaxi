export function availableGuides() {
  return GUIDES.filter((g) => allowedWindow(g.window, useSession.getState().session));
}
export function normalizeArabic(text: string) {
  return text
    .toLowerCase()
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[\u064B-\u065Fـ]/g, "");
}
export function searchGuides(query: string, window?: WindowId | null) {
  const terms = normalizeArabic(query)
    .split(/\s+/)
    .filter((v) => v.length > 1);
  return availableGuides()
    .map((g) => ({
      guide: g,
      score:
        terms.reduce(
          (n, word) =>
            n +
            (normalizeArabic(
              g.title + " " + g.keywords + " " + g.steps.map((s) => s.text).join(" "),
            ).includes(word)
              ? 1
              : 0),
          0,
        ) + (g.window === window ? 0.2 : 0),
    }))
    .filter((g) => !terms.length || g.score >= 1)
    .sort((a, b) => b.score - a.score)
    .slice(0, 6)
    .map((v) => v.guide);
}
export const guideTarget = (g: Guide): WorkspaceTarget => ({ window: g.window });
